// apps/web/src/lib/site.ts
// One place for how Wola describes itself to browsers, search engines and
// link previews, and for building a page's <head> metadata.
//
// Wola is a private, multi-tenant staff-loan system: every tenant lives on its
// own subdomain and almost every page is behind a login. So the policy is:
//   * only the sign-in page is indexable (it is the public front door);
//   * everything else is `noindex` (also sent as an X-Robots-Tag header, see
//     next.config.ts), because loan, employee and salary data must never be
//     crawled or cached by a search engine;
//   * canonical URLs and sitemap entries are built from the host the request
//     came in on — never a hard-coded domain — so a custom domain or a new
//     tenant subdomain just works.
import type { Metadata } from "next";
import { headers } from "next/headers";

export const SITE_NAME = "Wola";
export const SITE_TAGLINE = "Staff loan management";
export const SITE_DESCRIPTION =
  "Wola is staff loan management for employers: apply, approve, disburse and collect salary-deducted loans with clear rules, a full audit trail and one place for HR and finance.";

/** Origin of the host serving this request, e.g. https://acme.wola.africa.
 *  Falls back to SITE_URL (set it in production), then localhost. */
export async function siteOrigin(): Promise<string> {
  const h = await headers();
  const host = h.get("x-forwarded-host") ?? h.get("host");
  if (host) {
    const forwarded = h.get("x-forwarded-proto");
    const local = /^(localhost|127\.0\.0\.1|\[::1\])(:|$)|\.localhost(:|$)|\.local(:|$)/.test(host);
    const proto = forwarded ?? (local ? "http" : "https");
    return `${proto}://${host}`;
  }
  return process.env.SITE_URL?.replace(/\/$/, "") ?? "http://localhost:3000";
}

/** Link-preview images (generated by app/opengraph-image.tsx and
 *  app/twitter-image.tsx). Named explicitly because a page that defines its own
 *  openGraph/twitter metadata would otherwise drop the file-based images. */
export const SHARE_IMAGE_ALT = `${SITE_NAME} — ${SITE_TAGLINE.toLowerCase()}`;
const OG_IMAGES = [{ url: "/opengraph-image", width: 1200, height: 630, alt: SHARE_IMAGE_ALT }];
const TWITTER_IMAGES = [{ url: "/twitter-image", width: 1200, height: 630, alt: SHARE_IMAGE_ALT }];
export const SHARE_IMAGES = { openGraph: OG_IMAGES, twitter: TWITTER_IMAGES };

type PageMetaArgs = {
  /** The page's own name, e.g. "Loan products". Becomes "Loan products · Wola". */
  title: string;
  description: string;
  /** Path of this page, e.g. "/settings/products". Used for the canonical tag. */
  path: string;
  /** Only the public sign-in page sets this to true. */
  index?: boolean;
};

/** The <head> metadata for one page: title, description, canonical, robots and
 *  link-preview tags. Private pages are noindex/nofollow/noarchive. */
export function pageMeta({ title, description, path, index = false }: PageMetaArgs): Metadata {
  return {
    title,
    description,
    alternates: { canonical: path },
    robots: index
      ? { index: true, follow: true }
      : { index: false, follow: false, noarchive: true, nosnippet: true },
    openGraph: { title: `${title} · ${SITE_NAME}`, description, url: path, siteName: SITE_NAME, type: "website", images: OG_IMAGES },
    twitter: { card: "summary_large_image", title: `${title} · ${SITE_NAME}`, description, images: TWITTER_IMAGES },
  };
}
